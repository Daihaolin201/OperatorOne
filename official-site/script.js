const defaultLocale = 'en-GB';
let currentLocale = defaultLocale;

const phraseNode = document.getElementById('dynamic-phrase');
const yearNode = document.getElementById('year');
const cursorGlow = document.querySelector('.cursor-glow');
const scrollProgress = document.querySelector('.scroll-progress');
const metaDescription = document.querySelector('meta[name="description"]');

let phraseIndex = 0;
let phraseTimer = null;

function t(key) {
  return i18n[currentLocale][key] ?? i18n[defaultLocale][key] ?? key;
}

function applyTranslations() {
  document.documentElement.lang = currentLocale;
  document.title = t('meta.title');
  if (metaDescription) metaDescription.setAttribute('content', t('meta.description'));

  document.querySelectorAll('[data-i18n]').forEach((node) => {
    const key = node.dataset.i18n;
    node.textContent = t(key);
  });

  document.querySelectorAll('[data-i18n-placeholder]').forEach((node) => {
    const key = node.dataset.i18nPlaceholder;
    node.setAttribute('placeholder', t(key));
  });

  document.querySelectorAll('.lang-btn').forEach((btn) => {
    btn.classList.toggle('active', btn.dataset.lang === currentLocale);
  });

  resetDynamicPhrases();
}

function resetDynamicPhrases() {
  const phrases = i18n[currentLocale].dynamicPhrases || [];
  if (!phraseNode || !phrases.length) return;

  phraseIndex = 0;
  phraseNode.style.opacity = '1';
  phraseNode.textContent = phrases[0];

  if (phraseTimer) clearInterval(phraseTimer);
  phraseTimer = setInterval(() => {
    phraseIndex = (phraseIndex + 1) % phrases.length;
    phraseNode.style.opacity = '0';
    setTimeout(() => {
      phraseNode.textContent = phrases[phraseIndex];
      phraseNode.style.opacity = '1';
    }, 170);
  }, 2600);
}

if (yearNode) {
  yearNode.textContent = String(new Date().getFullYear());
}

if (cursorGlow) {
  window.addEventListener('pointermove', (event) => {
    cursorGlow.style.left = `${event.clientX}px`;
    cursorGlow.style.top = `${event.clientY}px`;
  });
}

if (scrollProgress) {
  const updateProgress = () => {
    const maxScroll = document.documentElement.scrollHeight - window.innerHeight;
    const ratio = maxScroll > 0 ? window.scrollY / maxScroll : 0;
    scrollProgress.style.width = `${Math.max(0, Math.min(1, ratio)) * 100}%`;
  };

  updateProgress();
  window.addEventListener('scroll', updateProgress, { passive: true });
  window.addEventListener('resize', updateProgress);
}

const revealObserver = new IntersectionObserver(
  (entries) => {
    entries.forEach((entry) => {
      if (entry.isIntersecting) entry.target.classList.add('is-visible');
    });
  },
  { threshold: 0.14 }
);

document.querySelectorAll('.reveal').forEach((node) => revealObserver.observe(node));

let counted = false;
const metrics = document.querySelector('.metrics');

function animateCounter(node, target) {
  const duration = 1200;
  const start = performance.now();

  const tick = (now) => {
    const progress = Math.min((now - start) / duration, 1);
    const eased = 1 - Math.pow(1 - progress, 3);
    node.textContent = Math.floor(eased * target).toLocaleString();
    if (progress < 1) requestAnimationFrame(tick);
  };

  requestAnimationFrame(tick);
}

if (metrics) {
  const metricObserver = new IntersectionObserver(
    (entries) => {
      const [entry] = entries;
      if (entry.isIntersecting && !counted) {
        counted = true;
        document.querySelectorAll('[data-counter]').forEach((node) => {
          animateCounter(node, Number(node.getAttribute('data-counter') || '0'));
        });
      }
    },
    { threshold: 0.42 }
  );

  metricObserver.observe(metrics);
}

const tiltCards = document.querySelectorAll('.tilt-card');
const maxTilt = 7;

tiltCards.forEach((card) => {
  card.addEventListener('pointermove', (event) => {
    const rect = card.getBoundingClientRect();
    const x = event.clientX - rect.left;
    const y = event.clientY - rect.top;

    const px = (x / rect.width) * 2 - 1;
    const py = (y / rect.height) * 2 - 1;

    card.style.transform = `perspective(900px) rotateY(${px * maxTilt}deg) rotateX(${py * -maxTilt}deg) translateY(-1px)`;
  });

  card.addEventListener('pointerleave', () => {
    card.style.transform = 'perspective(900px) rotateY(0deg) rotateX(0deg) translateY(0px)';
  });
});

const faqItems = document.querySelectorAll('.faq-item');
faqItems.forEach((item, index) => {
  if (index === 0) item.classList.add('open');

  const button = item.querySelector('.faq-q');
  button?.addEventListener('click', () => {
    const isOpen = item.classList.contains('open');
    faqItems.forEach((node) => node.classList.remove('open'));
    if (!isOpen) item.classList.add('open');
  });
});

